"""Conservative full/unmodified goods trade using actual stock and Native events.

Not a generic inventory editor. Gear, modifiers and partially consumed stacks
are rejected until their actual engine pricing/transactions are established.
"""

REG, LOCAL, TROOP, SCRIPT = 1 << 56, 17 << 56, 5 << 56, 13 << 56


def goods_trade(url, globals_, scripts, troop_count, item_count, market_menu_id):
    required = (
        "game_get_item_buy_price_factor",
        "game_get_item_sell_price_factor",
        "game_event_buy_item",
        "game_event_sell_item",
    )
    if "current_town" not in globals_ or any(name not in scripts for name in required):
        return [("eq", 0, 1)]
    mode, packed, price_bound = LOCAL + 5, LOCAL + 6, LOCAL + 16
    (
        town,
        merchant,
        source,
        destination,
        source_slot,
        expected_item,
        item,
        destination_slot,
        amount,
        maximum,
        price,
        factor,
        size,
        index,
        tmp,
        buyer,
        seller,
        buyer_gold,
        seller_gold,
        can_execute,
    ) = [LOCAL + i for i in range(25, 45)]
    return [
        ("eq", LOCAL + 9, market_menu_id),
        ("assign", town, globals_["current_town"]),
        ("eq", town, globals_.get("g_encountered_party", -1)),
        ("eq", globals_.get("g_player_is_captive", -1), 0),
        ("party_is_active", town),
        ("ge", mode, 0),
        ("le", mode, 3),
        ("ge", packed, 0),
        ("ge", price_bound, 0),
        ("le", price_bound, 1000000),
        ("store_mod", source_slot, packed, 10000),
        ("store_div", expected_item, packed, 10000),
        ("ge", expected_item, 0),
        ("lt", expected_item, item_count),
        ("party_get_slot", merchant, town, 23),
        ("ge", merchant, 1),
        ("lt", merchant, troop_count),
        ("assign", source, merchant),
        ("assign", destination, TROOP),
        ("try_begin",),
        ("or_eq", mode, 1),
        ("eq", mode, 3),
        ("assign", source, TROOP),
        ("assign", destination, merchant),
        ("try_end",),
        ("troop_get_inventory_capacity", size, source),
        ("ge", source_slot, 10),
        ("lt", source_slot, size),
        ("troop_get_inventory_slot", item, source, source_slot),
        ("eq", item, expected_item),
        ("assign", LOCAL + 10, -7),
        ("troop_get_inventory_slot_modifier", tmp, source, source_slot),
        ("eq", tmp, 0),
        ("assign", LOCAL + 10, -8),
        ("troop_inventory_slot_get_item_amount", amount, source, source_slot),
        ("troop_inventory_slot_get_item_max_amount", maximum, source, source_slot),
        ("eq", amount, maximum),
        ("assign", LOCAL + 10, -9),
        ("item_get_type", tmp, item),
        ("eq", tmp, 11),
        ("not_item_has_property", item, 0x1000),
        ("try_begin",),
        ("or_eq", mode, 0),
        ("eq", mode, 2),
        ("call_script", SCRIPT + scripts[required[0]], item),
        ("else_try",),
        ("call_script", SCRIPT + scripts[required[1]], item),
        ("try_end",),
        ("assign", factor, REG),
        ("ge", factor, 1),
        ("le", factor, 10000),
        ("store_item_value", price, item),
        ("val_mul", price, factor),
        ("val_div", price, 100),
        ("ge", price, 1),
        ("le", price, 1000000),
        ("assign", buyer, destination),
        ("assign", seller, source),
        ("store_troop_gold", buyer_gold, buyer),
        ("store_troop_gold", seller_gold, seller),
        ("assign", destination_slot, -1),
        ("troop_get_inventory_capacity", size, destination),
        ("try_for_range", index, 10, size),
        ("eq", destination_slot, -1),
        ("troop_get_inventory_slot", tmp, destination, index),
        ("lt", tmp, 0),
        ("assign", destination_slot, index),
        ("try_end",),
        ("assign", can_execute, 0),
        ("try_begin",),
        ("ge", destination_slot, 10),
        ("ge", buyer_gold, price),
        ("le", seller_gold, 2000000000),
        ("assign", can_execute, 1),
        ("try_end",),
        ("try_begin",),
        ("ge", mode, 2),
        ("assign", LOCAL + 10, -6),
        ("eq", price, price_bound),
        ("assign", LOCAL + 10, -5),
        ("ge", destination_slot, 10),
        ("assign", LOCAL + 10, -4),
        ("ge", buyer_gold, price),
        ("le", seller_gold, 2000000000),
        # Everything that can reject is checked BEFORE the first mutation.
        ("troop_set_inventory_slot", destination, destination_slot, item),
        ("troop_set_inventory_slot_modifier", destination, destination_slot, 0),
        ("try_begin",),
        ("ge", maximum, 1),
        ("troop_inventory_slot_set_item_amount", destination, destination_slot, amount),
        ("try_end",),
        ("troop_set_inventory_slot", source, source_slot, -1),
        ("troop_set_inventory_slot_modifier", source, source_slot, 0),
        ("troop_remove_gold", buyer, price),
        ("troop_add_gold", seller, price),
        ("try_begin",),
        ("eq", mode, 2),
        ("call_script", SCRIPT + scripts[required[2]], item, 0),
        ("else_try",),
        ("call_script", SCRIPT + scripts[required[3]], item, 0),
        ("try_end",),
        ("assign", LOCAL + 10, 0),
        ("else_try",),
        ("lt", mode, 2),
        ("assign", LOCAL + 10, 0),
        ("try_end",),
        ("eq", LOCAL + 10, 0),
        ("assign", REG + 20, LOCAL + 3),
        ("assign", REG + 21, mode),
        ("assign", REG + 22, item),
        ("assign", REG + 23, source_slot),
        ("assign", REG + 24, destination_slot),
        ("assign", REG + 25, price),
        ("assign", REG + 26, merchant),
        ("assign", REG + 27, town),
        ("store_troop_gold", REG + 28, TROOP),
        ("store_troop_gold", REG + 29, merchant),
        ("troop_get_inventory_slot", REG + 30, source, source_slot),
        ("assign", REG + 31, -1),
        ("assign", REG + 33, 0),
        ("try_begin",),
        ("ge", destination_slot, 10),
        ("troop_get_inventory_slot", REG + 31, destination, destination_slot),
        (
            "troop_inventory_slot_get_item_amount",
            REG + 33,
            destination,
            destination_slot,
        ),
        ("try_end",),
        ("troop_inventory_slot_get_item_amount", REG + 32, source, source_slot),
        ("assign", REG + 34, factor),
        ("assign", REG + 35, can_execute),
        ("str_store_string", 127, url),
        ("send_message_to_url", 127, 0),
    ]
